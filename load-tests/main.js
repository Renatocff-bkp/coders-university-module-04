import {
  buildOptions,
  requiredSeedCounts,
  resolveProfile,
} from "./lib/config.js";
import { validateSeed } from "./lib/data.js";
import { seed } from "./state.js";
import * as confirmAccountScenario from "./scenarios/confirm-account.js";
import * as forgotPasswordScenario from "./scenarios/forgot-password.js";
import * as healthScenario from "./scenarios/health.js";
import * as pingScenario from "./scenarios/ping.js";
import * as resetPasswordScenario from "./scenarios/reset-password.js";
import * as sessionScenario from "./scenarios/session.js";
import * as signInScenario from "./scenarios/sign-in.js";
import * as signOutScenario from "./scenarios/sign-out.js";
import * as signUpScenario from "./scenarios/sign-up.js";

const profile = resolveProfile();
const seedErrors = validateSeed(seed, requiredSeedCounts(profile));

if (seedErrors.length > 0) {
  throw new Error(
    [
      `Seed file is not ready for profile "${profile}":`,
      ...seedErrors.map((error) => `- ${error}`),
      'Run "npm run loadtest:seed" and try again.',
    ].join("\n"),
  );
}

export const options = buildOptions(profile);

export function health() {
  healthScenario.health();
}

export function ping() {
  pingScenario.ping();
}

export function signUp() {
  signUpScenario.signUp();
}

export function confirmAccount() {
  confirmAccountScenario.confirmAccount();
}

export function signIn() {
  signInScenario.signIn();
}

export function session() {
  sessionScenario.session();
}

export function signOut() {
  signOutScenario.signOut();
}

export function forgotPassword() {
  forgotPasswordScenario.forgotPassword();
}

export function resetPassword() {
  resetPasswordScenario.resetPassword();
}

export default function () {
  // All load is generated by the scenarios in `options.scenarios`.
}
